// Aktuális nyelv beállítása
function setSiteLanguage(lang) {
    if (!translations[lang]) return;
    
    localStorage.setItem('preferred_lang', lang);
    document.documentElement.lang = lang;
    
    // Arab (RTL) szövegirány kezelése
    if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
    }

    // Szövegek frissítése
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Menü gomb feliratának frissítése (pl. HU, EN)
    const currentBtn = document.getElementById('currentLangBtn');
    if (currentBtn) {
        currentBtn.innerHTML = lang.toUpperCase() + ' <span style="font-size: 0.6rem; opacity: 0.7;">▾</span>';
    }

    // Aktív jelölés a lenyílóban
    document.querySelectorAll('.lang-opt').forEach(opt => {
        if (opt.getAttribute('data-lang') === lang) {
            opt.classList.add('active');
        } else {
            opt.classList.remove('active');
        }
    });

    // Menü bezárása
    const dropdown = document.getElementById('langDropdown');
    if (dropdown) dropdown.classList.remove('open');
}

// Lenyíló ablak kapcsolása
function toggleLangDropdown(e) {
    if (e) e.stopPropagation();
    const dropdown = document.getElementById('langDropdown');
    if (dropdown) dropdown.classList.toggle('open');
}

// Kattintás a gombon kívülre -> bezárás
window.addEventListener('click', () => {
    const dropdown = document.getElementById('langDropdown');
    if (dropdown && dropdown.classList.contains('open')) {
        dropdown.classList.remove('open');
    }
});

// Inicializálás
document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('preferred_lang') || 'hu';
    setSiteLanguage(saved);
});
